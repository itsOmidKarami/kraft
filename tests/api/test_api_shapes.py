def _url(route: str, ids: dict[str, str]) -> str:
    path = route.removeprefix("GET ")
    query = {}
    for name, value in PROBES[route].items():
        value = ids.get(value, value)
        if "{" + name + "}" in path:
            path = path.replace("{" + name + "}", value)
        else:
            query[name] = value
    return f"{path}?{urlencode(query)}" if query else path


def collect(client, wid: str, filed: str, one_off: str) -> dict[str, dict]:
    """Each probed route's parameters and answer, `{"params", "shape"}`, the item `wid`
    standing in for `$ITEM`, `filed` for `$FILED` and `one_off` for `$ONE_OFF`."""
    item = client.get(f"/api/work-items/{wid}").json()
    docs = []
    for _ in range(100):  # the index links the spec node's documents a moment after its gate
        found = client.get(f"/api/work-items/{wid}/documents").json()["documents"]
        if docs := [d for d in found if d["source_kind"] == "session_summary"]:
            break
        time.sleep(0.05)
    ids = {
        "$ITEM": wid,
        "$FILED": filed,
        "$ONE_OFF": one_off,
        "$SESSION": item["worker_sessions"][0]["id"],
        "$DOC": docs[0]["document_id"],
        "$REPO": item["repo"],
    }
    out = {}
    for route in sorted(PROBES):
        r = client.get(_url(route, ids))
        assert r.status_code == 200, f"{route}: {r.status_code} {r.text[:300]}"
        shape = skeleton(r.json(), 1 if route in SHALLOW else 2)
        out[route] = {"params": PROBES[route], "shape": shape}
    return out


@pytest.fixture
def shapes(client, repo) -> dict[str, dict]:
    """An item at its first gate with a review thread, a paused one filed with
    a spec, a registered machine, and a chain draft: so the lists the probes read are not empty."""
    connect_repo(repo)
    wid = _post_default(client, repo)
    _poll_events(client, wid, "gate_requested")
    (repo / "spec.md").write_text("# The spec\n")
    filed = client.post(
        "/api/work-items",
        json={
            "title": "filed",
            "repo": str(repo),
            "attachments": [{"kind": "spec", "path": "spec.md"}],
        },
    ).json()["id"]
    client.post(f"/api/work-items/{wid}/threads", json={"body": "why?"}).raise_for_status()
    client.post("/api/workers", json={"name": "box", "capacity": 2}).raise_for_status()
    chain = "chains/default.yaml"
    text = client.get("/api/drafts/chains/default").json()["files"][chain]
    client.put(
        f"/api/drafts/chains/default/files/{chain}",
        json={"text": text.replace("approve the specification", "approve the spec")},
    ).raise_for_status()
    one_off = _one_off(client, repo, CUSTOM_ONE_OFF)
    return collect(client, wid, filed, one_off)


@pytest.mark.parametrize(
    "value, shape",
    [
        pytest.param(3, "_", id="scalar"),
        pytest.param({"b": 1, "a": "x"}, {"a": "_", "b": "_"}, id="dict"),
        pytest.param({"a": {"b": {"c": 1}}}, {"a": {"b": "_"}}, id="nested-past-depth"),
        pytest.param(
            [{"a": 1}, {"b": {"c": 2}}],
            [{"a": "_", "b": {"c": "_"}}],
            id="list-merges-element-keys",
        ),
        pytest.param({"a": []}, {"a": []}, id="empty-list"),
    ],
)
def test_skeleton(value, shape):
    assert skeleton(value) == shape


def test_every_get_route_is_shaped_or_skipped():
    routes = {f"GET {path}" for path, ops in app.openapi()["paths"].items() if "get" in ops}
    assert not set(PROBES) & set(SKIPS), "both probed and skipped"
    assert sorted(routes - set(PROBES) - set(SKIPS)) == [], (
        "a GET route nobody shaped: probe it in PROBES or say why not in SKIPS"
    )
    assert sorted((set(PROBES) | set(SKIPS)) - routes) == [], "no such route"
    assert set(SHALLOW) <= set(PROBES)


def test_a_shape_is_not_vacuous(shapes):
    assert [r for r, s in shapes.items() if s["shape"] in ([], {})] == [], (
        "an empty answer compares nothing: seed what it lists, or skip the route"
    )


def test_the_table_is_what_the_server_returns(shapes):
    if os.environ.get("WRITE_API_SHAPES"):
        TABLE.write_text(json.dumps({"_doc": DOC, "routes": shapes}, indent=1) + "\n")
    table = json.loads(TABLE.read_text())["routes"]
    assert shapes == table, "the server's answers changed: run `just shapes`, then update the mock"
