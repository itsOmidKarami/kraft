def skeleton(value: object, depth: int = 2) -> object:
    """`value`'s keys, `depth` dict levels down: a dict maps each key (sorted)
    to its value's skeleton one level shallower; a list is one element, the
    skeletons of all its elements with their keys merged (`[]` when empty), at
    the same depth; a scalar, or anything at depth 0, is `"_"`.
    `frontend/demo/apiShapes.test.ts` has the same function, row for row."""
    if isinstance(value, list):
        return [_merge([skeleton(v, depth) for v in value])] if value else []
    if not isinstance(value, dict) or depth == 0:
        return "_"
    return {k: skeleton(value[k], depth - 1) for k in sorted(value)}


def _merge(shapes: list[object]) -> object:
    dicts = [s for s in shapes if isinstance(s, dict)]
    if not dicts:
        lists = [s for s in shapes if isinstance(s, list) and s]
        return [_merge([x[0] for x in lists])] if lists else shapes[0]
    keys: dict[str, list[object]] = {}
    for d in dicts:
        for k, v in d.items():
            keys.setdefault(k, []).append(v)
    return {k: _merge(keys[k]) for k in sorted(keys)}


