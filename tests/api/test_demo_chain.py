"""The shipped chains as a real server freezes them, recorded for the dashboard demo.

`frontend/e2e/contract/mocks/shippedChains.json` holds what the demo's work items
run, for `default` and `quick-task`: an item's `chain_definition` and the `chain`
of its `materialized_chain`, from an item filed paused on the shipped library, so
its builtin tasks are the real ones (the suite's fake library turns them into
`true`). The demo builds its items on this file, so a change to a shipped chain
reaches the demo as a failure here until the file is rewritten: `just shapes`
does it (`WRITE_DEMO_CHAIN=1`)."""

from __future__ import annotations

import json
import os
import shutil

import pytest
from support.harness import _REPO_ROOT, connect_repo, seed_v1_library

TABLE = _REPO_ROOT / "frontend" / "e2e" / "contract" / "mocks" / "shippedChains.json"
DOC = (
    "Generated by tests/api/test_demo_chain.py (`just shapes`); never edit by hand. "
    "The shipped chains as the real server freezes them for an item filed paused: "
    "each one's `chain_definition`, and the `chain` of its `materialized_chain`. The "
    "dashboard demo's work items run them."
)


@pytest.fixture
def templates_dir(tmp_path):
    """The shipped library, harnesses and policy as they are, not the suite's fake agent library."""
    d = tmp_path / "templates"
    d.mkdir()
    shutil.copy(_REPO_ROOT / "config" / "policy.yaml", d / "policy.yaml")
    seed_v1_library(d)
    return d


def _task_kinds(chain: dict) -> set[str]:
    """The kinds of the tasks a frozen chain's nodes list, directly or under their steps."""
    tasks = []
    for node in chain["nodes"]:
        tasks += node.get("tasks") or []
        for step in node.get("steps") or []:
            tasks += step["tasks"]
    return {task["kind"] for task in tasks}


def _frozen(client, repo, template: str) -> dict:
    wid = client.post(
        "/api/work-items",
        json={"title": f"record {template}", "repo": str(repo), "chain_template": template},
    ).json()["id"]
    item = client.get(f"/api/work-items/{wid}").json()
    chain = json.loads(item["materialized_chain"])["chain"]
    return {"chain_definition": item["chain_definition"], "chain": chain}


def test_the_demos_chains_are_what_the_server_freezes(client, repo):
    connect_repo(repo)
    chains = {template: _frozen(client, repo, template) for template in ("default", "quick-task")}
    # What makes the recording the real chains, not the suite's: the tests task is the builtin.
    assert {"agent", "builtin", "forge"} <= _task_kinds(chains["default"]["chain"])
    recorded = {"_doc": DOC, "chains": chains}
    if os.environ.get("WRITE_DEMO_CHAIN"):
        TABLE.write_text(json.dumps(recorded, indent=1) + "\n")
    assert recorded == json.loads(TABLE.read_text()), (
        "a shipped chain changed: run `just shapes`, then update the demo's items"
    )
